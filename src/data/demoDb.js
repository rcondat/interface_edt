function makeSlot(id, index, startTime, endTime) {
  return {
    id,
    index,
    startTime,
    endTime,
    durationMinutes: 90,
    label: `${startTime} - ${endTime}`,
  };
}

function makeDay(id, weekId, date, weekdayIndex, weekdayLabel, options = {}) {
  return {
    id,
    weekId,
    date,
    weekdayIndex,
    weekdayLabel,
    isHoliday: false,
    isClosed: false,
    ...options,
  };
}

function makeGroup({
  id,
  label,
  groupSetId,
  promotionIds,
  studentCount = null,
  parentGroupIds = [],
  childGroupIds = [],
}) {
  return {
    id,
    label,
    groupSetId,
    promotionIds,
    studentCount,
    parentGroupIds,
    childGroupIds,
  };
}

